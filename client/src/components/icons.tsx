export type LinkIconName = keyof typeof LINK_ICONS;

export const LINK_ICON_NAMES = Object.keys(LINK_ICONS) as LinkIconName[];

export function isLinkIconName(value: string | null | undefined): value is LinkIconName {
  return !!value && value in LINK_ICONS;
}

export function LinkIcon({
  name,
  className = "",
  size = 16,
}: {
  name: string | null | undefined;
  className?: string;
  size?: number;
}) {
  const key = isLinkIconName(name) ? name : "link-2";
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
    >
      {LINK_ICONS[key]}
    </svg>
  );
}

export function IconPicker({
  value,
  onChange,
}: {
  value: string | null;
  onChange: (name: LinkIconName) => void;
}) {
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    function handleClick(e: MouseEvent) {
      if (ref.current && !ref.current.contains(e.target as Node)) {
        setOpen(false);
      }
    }
    document.addEventListener("mousedown", handleClick);
    return () => document.removeEventListener("mousedown", handleClick);
  }, []);

  return (
    <div ref={ref} className="relative">
      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        aria-label="Ikon kiválasztása"
        className="flex h-[42px] w-full items-center justify-center rounded-lg border border-ink-100 bg-ink-50/60 text-ink-700 outline-none transition hover:border-ink-300 focus:border-brand-400 focus:bg-surface focus:ring-2 focus:ring-brand-100"
      >
        <LinkIcon name={value} size={18} />
      </button>

      {open && (
        <div className="absolute z-50 mt-1 grid w-40 grid-cols-5 gap-1 rounded-lg border border-ink-100 bg-surface p-2 shadow-panel">
          {LINK_ICON_NAMES.map((name) => (
            <button
              key={name}
              type="button"
              onClick={() => {
                onChange(name);
                setOpen(false);
              }}
              aria-label={name}
              className="flex h-7 w-7 items-center justify-center rounded-md transition"
              style={{
                backgroundColor:
                  value === name ? "rgb(var(--brand-100))" : "transparent",
                color:
                  value === name ? "#2f6f5e" : "rgb(var(--ink-700))",
              }}
            >
              <LinkIcon name={name} size={15} />
            </button>
          ))}
        </div>
      )}
    </div>
  );
}
